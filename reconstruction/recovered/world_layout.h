// Recovered model: the World instance layout (227 ivars, offsets 4..3440).
//
// Every row is (offset, name, ivar cell) read out of the binary's own OBJC_IVAR_$_World.* cells - the
// same mechanism the getters use at run time. The Python contract test re-reads the symbol table and
// requires an exact match, so this cannot drift.
//
// Cross-checks worth keeping in mind when reading it:
//   * the clock/weather domain entries (worldTime 648, sunDirection 660, timeOfDayFraction 880, the four
//     weather floats, fastForward 934, ...) must agree with world_clock_domain.h, which this file
//     static_asserts for two of them;
//   * byte-sized entries are interleaved with 4-byte ones (interfaceOrientation 8 followed by
//     worldWidthMacro 12, supportsGyro 16 next to isObservingMotionEvents 17), so a reader must not assume
//     a stride - only the recorded offsets are facts.
//
// Deliberately not modelled: types. The table gives names, offsets and cells; claiming that
// `motionManager` is a MotionManager* would be inference rather than evidence.
