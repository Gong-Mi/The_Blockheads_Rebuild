constexpr bool offsetsAreSorted() {
    for (std::size_t i = 1; i < kWorldFields.size(); ++i)
        if (kWorldFields[i - 1].offset >= kWorldFields[i].offset) return false;
    return true;
}
static_assert(offsetsAreSorted(), "World layout must be sorted by offset and duplicate-free");

